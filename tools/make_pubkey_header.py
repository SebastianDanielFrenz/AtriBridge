"""Writes src/update_pubkey.h from the update signing key (needs `openssl` on PATH).
    python tools/make_pubkey_header.py PATH/TO/update_private.pem
The private key stays OUTSIDE the repository; the header holds only the public point (X, Y)."""
import subprocess, sys, os
key = sys.argv[1]
der = subprocess.run(["openssl", "ec", "-in", key, "-pubout", "-outform", "DER"], capture_output=True, check=True).stdout
pt = der[-65:]
assert pt[0] == 4 and len(pt) == 65
x, y = pt[1:33], pt[33:]
fmt = lambda b: ", ".join("0x%02x" % c for c in b)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "update_pubkey.h")
open(out, "w").write("// Generated by tools/make_pubkey_header.py: the public key updates must be signed with (ECDSA P-256).\n"
                     "#pragma once\n#include <cstdint>\nstatic const uint8_t kUpdateKeyX[32] = {%s};\nstatic const uint8_t kUpdateKeyY[32] = {%s};\n" % (fmt(x), fmt(y)))
print("wrote", os.path.normpath(out))
